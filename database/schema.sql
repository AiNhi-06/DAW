CREATE INDEX IF NOT EXISTS idx_ho_so_ma_thi_sinh ON ho_so(ma_thi_sinh);
CREATE INDEX IF NOT EXISTS idx_ho_so_trang_thai ON ho_so(trang_thai);
CREATE INDEX IF NOT EXISTS idx_giay_to_ma_ho_so ON giay_to(ma_ho_so);
CREATE INDEX IF NOT EXISTS idx_ocr_ma_giay_to ON ocr_result(ma_giay_to);
CREATE INDEX IF NOT EXISTS idx_canh_bao_ma_ho_so ON canh_bao(ma_ho_so);

CREATE OR REPLACE VIEW v_tong_quan_ho_so AS
SELECT
    hs.ma_ho_so,
    ts.ma_thi_sinh,
    ts.ho_ten,
    ts.cccd,
    ts.email,
    hs.ngay_nop,
    hs.trang_thai,
    nd.ho_ten AS can_bo_phu_trach,
    COUNT(DISTINCT gt.ma_giay_to) AS so_giay_to,
    COUNT(DISTINCT cb.ma_canh_bao) AS so_canh_bao
FROM ho_so hs
JOIN thi_sinh ts ON ts.ma_thi_sinh = hs.ma_thi_sinh
LEFT JOIN nguoi_dung nd ON nd.ma_nguoi_dung = hs.ma_nguoi_dung
LEFT JOIN giay_to gt ON gt.ma_ho_so = hs.ma_ho_so
LEFT JOIN canh_bao cb ON cb.ma_ho_so = hs.ma_ho_so
GROUP BY hs.ma_ho_so, ts.ma_thi_sinh, ts.ho_ten, ts.cccd, ts.email,
         hs.ngay_nop, hs.trang_thai, nd.ho_ten;
